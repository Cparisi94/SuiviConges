-- 0007 — délégation des valideurs.
--
-- Un valideur peut déléguer à son propre valideur : automatiquement quand il est absent (users.delegate_auto)
-- et/ou sur des périodes explicites (table delegations), même s'il n'a pas de congés.
-- Pendant une délégation, le délégataire est aussi prévenu des demandes (mail avec boutons Valider / Refuser).
ALTER TABLE users ADD COLUMN delegate_auto INTEGER NOT NULL DEFAULT 0;

CREATE TABLE delegations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,   -- le valideur qui délègue
    start_date TEXT NOT NULL,                                           -- AAAA-MM-JJ, inclus
    end_date TEXT NOT NULL,                                             -- AAAA-MM-JJ, inclus
    created_at TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX idx_delegations_user ON delegations(user_id, start_date, end_date);
