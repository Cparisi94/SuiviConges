-- 0003 — clés API pour les applications tierces (accès à l'API /api/v1).
-- La clé en clair n'est jamais stockée : seule son empreinte SHA-256 l'est.
CREATE TABLE api_keys (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    key_prefix TEXT NOT NULL,                  -- 8 premiers caractères, pour reconnaître la clé
    key_hash TEXT NOT NULL UNIQUE,
    scopes TEXT NOT NULL DEFAULT '',           -- périmètres séparés par des virgules (ex. agents:read,requests:read)
    allowed_ips TEXT NOT NULL DEFAULT '',      -- adresses ou réseaux CIDR séparés par des virgules ; vide = toutes
    expires_at TEXT NOT NULL DEFAULT '',       -- AAAA-MM-JJ ; vide = sans expiration
    actif INTEGER NOT NULL DEFAULT 1,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS'),
    last_used_at TEXT
);

-- Journal des appels (méthode, chemin, statut, IP) : aucun contenu de requête ni de réponse.
CREATE TABLE api_key_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_id INTEGER REFERENCES api_keys(id) ON DELETE CASCADE,
    at TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS'),
    method TEXT NOT NULL,
    path TEXT NOT NULL,
    status INTEGER NOT NULL,
    ip TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_api_key_logs_key ON api_key_logs(key_id, id DESC);
