-- 0004 — matricule des agents, journal des connexions, journal des e-mails.

-- Matricule (clé de rapprochement avec Sedit RH). Unique par compte lorsqu'il est renseigné.
ALTER TABLE users ADD COLUMN matricule TEXT NOT NULL DEFAULT '';
ALTER TABLE agents ADD COLUMN matricule TEXT NOT NULL DEFAULT '';
CREATE UNIQUE INDEX idx_users_matricule ON users(matricule) WHERE matricule <> '';
CREATE INDEX idx_agents_matricule ON agents(matricule) WHERE matricule <> '';

-- Journal des connexions : qui, quand, depuis quelle adresse, avec quel résultat.
-- Pas de clé étrangère : on garde la trace même si le compte est supprimé.
CREATE TABLE login_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS'),
    event TEXT NOT NULL,                      -- connexion | echec | deconnexion | en_tant_que | fin_en_tant_que
    login TEXT NOT NULL DEFAULT '',           -- identifiant saisi
    user_id INTEGER,
    success INTEGER NOT NULL DEFAULT 1,
    reason TEXT NOT NULL DEFAULT '',          -- inconnu | mot_de_passe | desactive | service_ad | limite | …
    method TEXT NOT NULL DEFAULT '',          -- local | ad | secours
    ip TEXT NOT NULL DEFAULT '',
    user_agent TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_login_logs_at ON login_logs(at DESC, id DESC);
CREATE INDEX idx_login_logs_login ON login_logs(login);

-- Journal des e-mails envoyés (ou tentés) par l'application.
CREATE TABLE mail_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS'),
    to_addr TEXT NOT NULL DEFAULT '',
    subject TEXT NOT NULL DEFAULT '',
    template TEXT NOT NULL DEFAULT '',        -- clé du message automatique (nouvelle_demande, relance_demandes…)
    status TEXT NOT NULL,                     -- envoye | echec | non_envoye
    error TEXT NOT NULL DEFAULT '',
    body TEXT NOT NULL DEFAULT '',            -- texte envoyé
    request_id INTEGER                        -- demande concernée, le cas échéant
);
CREATE INDEX idx_mail_logs_at ON mail_logs(at DESC, id DESC);
