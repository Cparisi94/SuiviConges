-- 0001 — schéma initial de l'application « Suivi des congés ».
-- Le marqueur __SCHEMA__ est remplacé par le schéma configuré (CONGES_PG_SCHEMA).
-- Les dates restent stockées en texte « AAAA-MM-JJ HH:MM:SS » (comme dans la version SQLite)
-- afin de ne pas modifier la logique métier ; leur conversion en TIMESTAMPTZ fera l'objet d'une étape dédiée.

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login TEXT NOT NULL UNIQUE,
    nom TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    mot_de_passe TEXT NOT NULL,
    admin INTEGER NOT NULL DEFAULT 0,
    role TEXT NOT NULL DEFAULT 'secteur',
    parent_id INTEGER REFERENCES users(id),
    actif INTEGER NOT NULL DEFAULT 1,
    cree_le TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE user_audit (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    target_login TEXT NOT NULL DEFAULT '',
    actor_id INTEGER,
    actor_login TEXT NOT NULL DEFAULT '',
    action TEXT NOT NULL,
    field TEXT NOT NULL DEFAULT '',
    old_value TEXT NOT NULL DEFAULT '',
    new_value TEXT NOT NULL DEFAULT '',
    comment TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX idx_user_audit_created ON user_audit(created_at);

CREATE TABLE agents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    agent_user_id INTEGER REFERENCES users(id),
    nom TEXT NOT NULL,
    prenom TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    validator_id INTEGER REFERENCES users(id),
    year INTEGER NOT NULL DEFAULT 2027,
    params TEXT NOT NULL DEFAULT '{}',
    periods TEXT NOT NULL DEFAULT '[]',
    is_manager INTEGER NOT NULL DEFAULT 0,
    cree_le TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS'),
    modifie_le TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX idx_agents_agent_user ON agents(agent_user_id);
CREATE INDEX idx_agents_user ON agents(user_id);

CREATE TABLE cells (
    agent_id INTEGER NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    jour INTEGER NOT NULL,
    code TEXT NOT NULL,
    PRIMARY KEY (agent_id, jour)
);

CREATE TABLE settings (
    cle TEXT PRIMARY KEY,
    valeur TEXT NOT NULL
);

CREATE TABLE leave_requests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id INTEGER NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id),
    year INTEGER NOT NULL,
    request_type TEXT NOT NULL DEFAULT 'absence',
    code TEXT NOT NULL,
    cells TEXT NOT NULL DEFAULT '[]',
    days DOUBLE PRECISION NOT NULL DEFAULT 0,
    hours DOUBLE PRECISION NOT NULL DEFAULT 0,
    absence_date TEXT NOT NULL DEFAULT '',
    start_time TEXT NOT NULL DEFAULT '',
    end_time TEXT NOT NULL DEFAULT '',
    valid_until TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'en_attente',
    validator_id INTEGER REFERENCES users(id),
    validator_account_name TEXT NOT NULL DEFAULT '',
    validator_manager_name TEXT NOT NULL DEFAULT '',
    comment TEXT NOT NULL DEFAULT '',
    decision_comment TEXT NOT NULL DEFAULT '',
    cree_le TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS'),
    soumis_le TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS'),
    decide_le TEXT,
    attachment_name TEXT NOT NULL DEFAULT '',
    attachment_file TEXT NOT NULL DEFAULT '',
    attachment_size INTEGER NOT NULL DEFAULT 0,
    attachment_mime TEXT NOT NULL DEFAULT '',
    cancel_requested_at TEXT,
    cancel_requested_by INTEGER,
    cancel_reason TEXT NOT NULL DEFAULT '',
    cancel_decided_at TEXT,
    cancel_decided_by INTEGER,
    cancel_decision_comment TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_leave_requests_agent ON leave_requests(agent_id);
CREATE INDEX idx_leave_requests_status ON leave_requests(status);
CREATE INDEX idx_leave_requests_validator ON leave_requests(validator_id);
CREATE INDEX idx_leave_requests_user ON leave_requests(user_id);

CREATE TABLE leave_request_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INTEGER NOT NULL REFERENCES leave_requests(id) ON DELETE CASCADE,
    action TEXT NOT NULL,
    actor_id INTEGER REFERENCES users(id),
    comment TEXT NOT NULL DEFAULT '',
    cree_le TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX idx_leave_events_request ON leave_request_events(request_id);

CREATE TABLE hourly_absences (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id INTEGER NOT NULL REFERENCES agents(id) ON DELETE CASCADE,
    year INTEGER NOT NULL,
    absence_date TEXT NOT NULL,
    code TEXT NOT NULL,
    start_time TEXT NOT NULL DEFAULT '',
    end_time TEXT NOT NULL DEFAULT '',
    hours DOUBLE PRECISION NOT NULL DEFAULT 0,
    request_id INTEGER REFERENCES leave_requests(id) ON DELETE SET NULL,
    created_by INTEGER REFERENCES users(id),
    cree_le TEXT NOT NULL DEFAULT to_char(localtimestamp, 'YYYY-MM-DD HH24:MI:SS')
);
CREATE INDEX idx_hourly_agent_date ON hourly_absences(agent_id, absence_date);
CREATE INDEX idx_hourly_request ON hourly_absences(request_id);
